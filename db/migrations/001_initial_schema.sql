BEGIN;

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  username TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('subject_teacher', 'homeroom_teacher', 'principal')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS school_settings (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  name TEXT,
  logo_url TEXT,
  city TEXT,
  principal_name TEXT
);

INSERT INTO school_settings (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS classes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  grade INTEGER NOT NULL CHECK (grade BETWEEN 1 AND 6),
  phase TEXT NOT NULL CHECK (phase IN ('A', 'B', 'C')),
  homeroom_teacher TEXT,
  UNIQUE (name, grade)
);

CREATE TABLE IF NOT EXISTS students (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  class_id INTEGER NOT NULL REFERENCES classes(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS academic_terms (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academic_year TEXT NOT NULL,
  semester INTEGER NOT NULL CHECK (semester IN (1, 2)),
  starts_on DATE NOT NULL,
  ends_on DATE NOT NULL,
  UNIQUE (academic_year, semester),
  CHECK (starts_on <= ends_on)
);

CREATE TABLE IF NOT EXISTS subjects (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  grade INTEGER NOT NULL CHECK (grade BETWEEN 1 AND 6),
  phase TEXT NOT NULL CHECK (phase IN ('A', 'B', 'C')),
  UNIQUE (name, grade, phase)
);

CREATE TABLE IF NOT EXISTS learning_objectives (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id INTEGER NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  code TEXT,
  description TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS score_rules (
  term_id INTEGER NOT NULL REFERENCES academic_terms(id) ON DELETE CASCADE,
  subject_id INTEGER NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  formative_weight DOUBLE PRECISION NOT NULL CHECK (formative_weight BETWEEN 0 AND 100),
  summative_weight DOUBLE PRECISION NOT NULL CHECK (summative_weight BETWEEN 0 AND 100),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (term_id, subject_id),
  CHECK (formative_weight + summative_weight = 100)
);

CREATE TABLE IF NOT EXISTS assessments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  objective_id INTEGER NOT NULL REFERENCES learning_objectives(id) ON DELETE CASCADE,
  term_id INTEGER NOT NULL REFERENCES academic_terms(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('formative', 'summative')),
  title TEXT NOT NULL,
  score DOUBLE PRECISION NOT NULL CHECK (score >= 0),
  max_score DOUBLE PRECISION NOT NULL CHECK (max_score > 0 AND score <= max_score),
  assessed_on DATE NOT NULL,
  created_by INTEGER NOT NULL REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS narratives (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  subject_id INTEGER NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  term_id INTEGER NOT NULL REFERENCES academic_terms(id) ON DELETE CASCADE,
  content TEXT NOT NULL,
  reviewed_by INTEGER REFERENCES users(id),
  reviewed_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (student_id, subject_id, term_id)
);

CREATE TABLE IF NOT EXISTS report_sections (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  term_id INTEGER NOT NULL REFERENCES academic_terms(id) ON DELETE CASCADE,
  section_key TEXT NOT NULL CHECK (section_key IN ('kokurikuler', 'profil', 'ekstrakurikuler')),
  content TEXT NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (student_id, term_id, section_key)
);

CREATE TABLE IF NOT EXISTS attendance_imports (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_hash TEXT NOT NULL,
  imported_by INTEGER NOT NULL REFERENCES users(id),
  imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  rows_added INTEGER NOT NULL DEFAULT 0,
  rows_unchanged INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS attendance (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  attendance_date DATE NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('A', 'H', 'I', 'S')),
  import_id INTEGER NOT NULL REFERENCES attendance_imports(id),
  UNIQUE (student_id, attendance_date)
);

CREATE TABLE IF NOT EXISTS report_states (
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  term_id INTEGER NOT NULL REFERENCES academic_terms(id) ON DELETE CASCADE,
  status TEXT NOT NULL CHECK (status IN ('draft', 'homeroom_review', 'principal_approval', 'finalized')),
  homeroom_reviewed_by INTEGER REFERENCES users(id),
  homeroom_reviewed_at TIMESTAMPTZ,
  approved_by INTEGER REFERENCES users(id),
  approved_at TIMESTAMPTZ,
  finalized_by INTEGER REFERENCES users(id),
  finalized_at TIMESTAMPTZ,
  PRIMARY KEY (student_id, term_id)
);

CREATE TABLE IF NOT EXISTS audit_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  action TEXT NOT NULL,
  entity TEXT NOT NULL,
  entity_id TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS sessions_expiry_idx ON sessions (expires_at);
CREATE INDEX IF NOT EXISTS students_class_idx ON students (class_id);
CREATE INDEX IF NOT EXISTS assessments_student_term_idx ON assessments (student_id, term_id);
CREATE INDEX IF NOT EXISTS narratives_student_term_idx ON narratives (student_id, term_id);
CREATE INDEX IF NOT EXISTS attendance_student_date_idx ON attendance (student_id, attendance_date);

REVOKE ALL ON SCHEMA public FROM anon, authenticated, service_role;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
